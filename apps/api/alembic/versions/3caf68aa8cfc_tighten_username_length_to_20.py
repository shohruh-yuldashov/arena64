branch_labels: Sequence[str] | None = None
depends_on: Sequence[str] | None = None

SCHEMA = "users"
CHECK_NAME = "ck_user__username_length"
FOLDED_INDEX = "uq_user__username_folded"
FOLD_EXPRESSION = "lower(normalize(username, NFKC))"


def _resize_username(*, new_length: int, old_length: int, check_upper_bound: int) -> None:
    """One routine for both directions — they differ only in the numbers.

    Written once rather than twice because a downgrade that is a
    hand-mirrored copy of an upgrade is where the two silently stop
    matching, and this migration's whole risk is in the *sequence*, not
    the values.
    """
    op.drop_constraint(op.f(CHECK_NAME), "user", schema=SCHEMA, type_="check")

    # Dropping the generated column also drops `uq_user__username_folded`,
    # which is defined over it — recreated explicitly below.
    op.drop_column("user", "username_folded", schema=SCHEMA)

    op.alter_column(
        "user",
        "username",
        existing_type=sa.VARCHAR(length=old_length),
        type_=sa.String(length=new_length),
        existing_nullable=False,
        schema=SCHEMA,
    )

    op.add_column(
        "user",
        sa.Column(
            "username_folded",
            sa.String(length=new_length),
            sa.Computed(FOLD_EXPRESSION, persisted=True),
            nullable=False,
        ),
        schema=SCHEMA,
    )
    op.create_index(FOLDED_INDEX, "user", ["username_folded"], unique=True, schema=SCHEMA)

    op.create_check_constraint(
        op.f(CHECK_NAME),
        "user",
        f"char_length(username) BETWEEN 3 AND {check_upper_bound}",
        schema=SCHEMA,
    )


