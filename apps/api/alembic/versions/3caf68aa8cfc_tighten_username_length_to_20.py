"""tighten username length to 20

Revision ID: 3caf68aa8cfc
Revises: 7ed700e67f2a
Create Date: 2026-08-01 00:43:12.553627

Autogenerated, then adjusted — database.md §16: "Autogenerate is a draft,
never a commit."

Alembic detected both `VARCHAR(32) -> VARCHAR(20)` column changes (thanks
to `compare_type=True`, set in `env.py` for exactly this reason). What it
did **not** detect is the `ck_user__username_length` CHECK constraint,
which still reads `BETWEEN 3 AND 32`: Alembic does not compare check
constraints at all, so an autogenerated-and-accepted migration would have
left the database enforcing the old bound while the application enforced
the new one. That is the silent half-migration BE-06 cares about — the
constraint is the authoritative guard, so leaving it stale means the
guard and the domain disagree.

The constraint is therefore dropped and recreated by hand, in both
directions.

**The generated column has to be demolished and rebuilt.** PostgreSQL
refuses `ALTER COLUMN username TYPE ...` outright while `username_folded`
exists, with `cannot alter type of a column used by a generated column` —
a generated column's expression pins the type of everything it reads.
Alembic's autogenerated `alter_column` pair therefore cannot work here at
all, in either direction. The sequence has to be: drop the dependent
generated column (which takes its unique index with it), widen or narrow
`username`, then recreate the generated column and its index.

That also means this migration briefly drops `uq_user__username_folded`,
the constraint enforcing case-insensitive username uniqueness (UP-1). It
is inside one transaction, so no window exists where a concurrent writer
could slip a duplicate in — PostgreSQL's DDL is transactional, and this
is one of the places that property is doing real work rather than being
a nicety.

**Ordering matters.** The CHECK is dropped first and recreated last,
because PostgreSQL validates a new CHECK against existing rows and a
stale bound would contradict the new column width in between.

**`op.f()` around the constraint name is load-bearing.** Without it,
Alembic runs the name through `Base.metadata`'s naming convention
(`ck_%(table_name)s__%(constraint_name)s`, database.md §2) and produces
`ck_user__ck_user__username_length` — a double prefix that matches
nothing, so the migration dies on `constraint ... does not exist`.
`op.f()` marks a name as already-final. Any future migration touching a
named constraint needs the same treatment; the trap is that it fails only
at run time, never at import or review.

**Data safety.** `VARCHAR(32) -> VARCHAR(20)` fails outright if any row
holds a longer value, and hyphenated usernames (permitted before this
revision, not after) would also become unreachable through the
application. Neither case exists — the table is empty in every
environment — but a future run against real data needs a backfill first,
which is why this is stated rather than assumed.
"""

from collections.abc import Sequence

import sqlalchemy as sa

from alembic import op

